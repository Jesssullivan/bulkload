def esc(text: str) -> str:
    out = []
    for ch in text:
        o = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif 0xDC80 <= o <= 0xDCFF:
            out.append(f"\\x{o & 0xFF:02x}")
        elif o < 0x20 or o == 0x7F:
            out.append(f"\\x{o:02x}")
        else:
            out.append(ch)
    return "".join(out)


def walk(corpus: Path) -> list[tuple[str, os.stat_result]]:
    out = []
    stack = [""]
    while stack:
        rel = stack.pop()
        with os.scandir(corpus / rel if rel else corpus) as entries:
            for entry in entries:
                child = f"{rel}/{entry.name}" if rel else entry.name
                info = entry.stat(follow_symlinks=False)
                out.append((child, info))
                if stat.S_ISDIR(info.st_mode):
                    stack.append(child)
    out.sort(key=lambda row: os.fsencode(row[0]))
    return out


def read_head(path: Path, size: int) -> bytes:
    try:
        with path.open("rb") as handle:
            return handle.read(size)
    except OSError:
        return b""


def beside_sqlite(corpus: Path, rel: str) -> bool:
    """Whether `rel` is a `<db>-shm` with a SQLite database `<db>` beside it."""
    return rel.endswith("-shm") and read_head(corpus / rel[:-4], 16) == SQLITE_MAGIC


def wal_frames(wal: bytes) -> tuple[list[int], dict]:
    """The page numbers of a WAL's valid frames, and the wal-index facts.

    A frame is valid while its salts are the header's and its checksum
    continues the chain (wal.c walDecodeFrame); the first invalid frame ends
    the log. `commit` is (mxFrame, nPage, checksum) at the last commit frame.
    """
    facts: dict = {"commit": (0, 0, 0, 0), "big": False, "page": 0, "salts": b""}
    if len(wal) < 32:
        return [], facts
    magic, _version, page, _seq, salt1, salt2, c1, c2 = struct.unpack(">8I", wal[:32])
    big = bool(magic & 1)
    s0, s1 = wal_checksum(wal[:24], big, 0, 0)
    facts.update(big=big, page=page, salts=wal[16:24], commit=(0, 0, s0, s1))
    if magic not in (0x377F0682, 0x377F0683) or (s0, s1) != (c1, c2) or page < 512:
        return [], facts
    frames: list[int] = []
    pos = 32
    while pos + 24 + page <= len(wal):
        pgno, truncate, f1, f2, k1, k2 = struct.unpack_from(">6I", wal, pos)
        if pgno == 0 or (f1, f2) != (salt1, salt2):
            break
        s0, s1 = wal_checksum(wal[pos : pos + 8], big, s0, s1)
        s0, s1 = wal_checksum(wal[pos + 24 : pos + 24 + page], big, s0, s1)
        if (s0, s1) != (k1, k2):
            break
        frames.append(pgno)
        if truncate:
            facts["commit"] = (len(frames), truncate, s0, s1)
        pos += 24 + page
    return frames, facts


def wal_index_tables(frames: list[int], regions: int) -> bytes:
    """Bytes [WALINDEX_HDR, end) of the wal-index of `frames` (wal.c
    walIndexAppend): per region, the page number of each frame, then a hash
    table of 1-based frame slots with linear probing."""
    out = bytearray(regions * WALINDEX_PGSZ)
    for frame, pgno in enumerate(frames, 1):
        region = (frame + HASH_NPAGE - HASH_NPAGE_ONE - 1) // HASH_NPAGE
        zero = 0 if region == 0 else HASH_NPAGE_ONE + (region - 1) * HASH_NPAGE
        slot = frame - zero
        base = region * WALINDEX_PGSZ
        first = base + (WALINDEX_HDR if region == 0 else 0)
        struct.pack_into("=I", out, first + (slot - 1) * 4, pgno)
        table = base + HASH_NPAGE * 4
        key = (pgno * 383) & (HASH_NSLOT - 1)
        while struct.unpack_from("=H", out, table + key * 2)[0]:
            key = (key + 1) & (HASH_NSLOT - 1)
        struct.pack_into("=H", out, table + key * 2, slot)
    return bytes(out[WALINDEX_HDR:])


def wal_index_problem(corpus: Path, rel: str) -> str | None:
    """Why `rel` is not exactly the wal-index of the WAL database beside it.

    The exemption is narrow. The database must be in WAL mode (header bytes
    18 and 19 are 2), and the file must be the index a reader rebuilds from
    the `-wal` beside it: its size the regions those frames need, both header
    copies equal with a valid checksum, the WAL's salts, page size, frame
    count and commit checksum, and page and hash tables exactly those of the
    frames. Only WalCkptInfo, the readers' marks, is free (40 bytes).
    """
    head = read_head(corpus / rel[:-4], 20)
    if head[:16] != SQLITE_MAGIC or head[18:20] != b"\x02\x02":
        return "the database beside it is not in WAL mode"
    path = corpus / rel
    wal_path = corpus / (rel[:-4] + "-wal")
    try:
        size = os.lstat(path).st_size
        wal_size = os.lstat(wal_path).st_size if os.path.lexists(wal_path) else 0
        if wal_size > LEAK_SCAN_LIMIT or size > LEAK_SCAN_LIMIT:
            return "larger than any wal-index this corpus can need"
        frames, facts = wal_frames(wal_path.read_bytes() if wal_size else b"")
        shm = path.read_bytes()
    except OSError as err:
        return f"unreadable: {err}"
    regions = (len(frames) + HASH_NPAGE - HASH_NPAGE_ONE - 1) // HASH_NPAGE + 1
    if len(shm) != regions * WALINDEX_PGSZ:
        return f"size {len(shm)}, not the {regions} region(s) its WAL needs"
    hdr = shm[:48]
    version, _unused, _change, init, big, page = struct.unpack_from("=IIIBBH", hdr)
    mx, npage, k0, k1 = struct.unpack_from("=IIII", hdr, 16)
    page_code = (facts["page"] & 0xFF00) | (facts["page"] >> 16)
    mx_want, npage_want, s0, s1 = facts["commit"]
    # The header checksum reads native words (walChecksumBytes nativeCksum=1).
    native = wal_checksum(hdr[:40], sys.byteorder == "big", 0, 0)
    checks = (
        hdr == shm[48:96],
        version == WALINDEX_VERSION and init == 1 and big == int(facts["big"]),
        (mx, npage) == (mx_want, npage_want),
        not mx or (page, k0, k1) == (page_code, s0, s1),
        not mx or hdr[32:40] == facts["salts"],
        native == struct.unpack_from("=II", hdr, 40),
        struct.unpack_from("=I", shm, 96)[0] <= mx,
        shm[WALINDEX_HDR:] == wal_index_tables(frames, regions),
    )
    if not all(checks):
        return "its header or tables are not those of the WAL beside it"
    return None


def sealed_walk(
    corpus: Path, allow_shm: bool = True
) -> tuple[list[tuple[str, os.stat_result]], list[str]]:
    """The walk minus exempt SQLite wal-index files, and those files.

    Any WAL-aware opener creates <db>-shm, read-only included (bulkload's own
    provider_sqlite backup does), and bulkload never carries -shm bytes. So
    on an unsealed copy the exact wal-index of a WAL database
    (`wal_index_problem`) is reported, never sealed: a first measurement pass
    must not stop the next `mutate` (OI-1003-Q35). Every other file stays in
    the walk, and so does every -shm once `allow_shm` is false (a sealed
    copy, where no reader can create one).
    """
    kept, shm = [], []
    for rel, info in walk(corpus):
        if (
            allow_shm
            and stat.S_ISREG(info.st_mode)
            and beside_sqlite(corpus, rel)
            and wal_index_problem(corpus, rel) is None
        ):
            shm.append(rel)
        else:
            kept.append((rel, info))
    return kept, shm


def index_logical(data: bytes) -> bytes:
    """A git index without its stat words and trailing checksum.

    The checksum is checked first: index.skipHash is pinned false, so the
    trailer is the SHA-1 of everything before it, and a corrupt one (which
    `git fsck` refuses) is a problem, not a normalised difference.
    """
    if data[:4] != b"DIRC":
        raise CorpusError("not a DIRC index")
    if len(data) < 32 or hashlib.sha1(data[:-20]).digest() != data[-20:]:
        raise CorpusError("index checksum does not match its contents")
    version, count = struct.unpack(">II", data[4:12])
    if version not in (2, 3):
        raise CorpusError(f"index version {version}")
    out = bytearray(data[:12])
    pos = 12
    for _ in range(count):
        mode = struct.unpack_from(">I", data, pos + 24)[0]
        out += struct.pack(">10I", 0, 0, 0, 0, 0, 0, mode, 0, 0, 0)
        flags = struct.unpack_from(">H", data, pos + 60)[0]
        name = pos + (64 if flags & 0x4000 else 62)
        # On disk an entry is padded with 1-8 NULs to a multiple of 8 bytes.
        size = (data.index(b"\0", name) - pos + 8) & ~7
        out += data[pos + 40 : pos + size]
        pos += size
    extensions = pos
    tail = len(data) - 20
    while pos < tail:
        sig = data[pos : pos + 4]
        if sig in (b"UNTR", b"FSMN", b"link"):
            raise CorpusError(f"stat-bearing index extension {sig.decode()}")
        pos += 8 + struct.unpack_from(">I", data, pos + 4)[0]
    if pos != tail:
        raise CorpusError("index extensions overrun")
    return bytes(out + data[extensions:tail])


def is_gitdir_name(name: str) -> bool:
    return name == ".git" or name.endswith(".git")


def entry_class(parts: list[str], kind: str, head: bytes) -> str:
    """The estate class of one manifest entry; the first matching rule wins.

    git-history is all of the #48 repository. git-admin is everything inside
    a git directory (`.git`, a bare `*.git`, `git/mirrors`) plus each linked
    worktree's `.git` file. git-worktree is a linked worktree's checkout, and
    git-checkout is the rest of `git/`. Outside `git/`, a SQLite database or
    `-wal` is sqlite wherever it lives; then the top-level area decides.
    """
    top = parts[0]
    if top == "git" and len(parts) > 1:
        if f"git/{parts[1]}" == HISTORY_REPO:
            return "git-history"
        if parts[1] == "mirrors" or any(is_gitdir_name(p) for p in parts):
            return "git-admin"
        agent = any(
            parts[k] == ".claude" and parts[k + 1] == "worktrees"
            for k in range(1, len(parts) - 2)
        )
        if parts[1].endswith(".worktrees") or agent:
            return "git-worktree"
        return "git-checkout"
    if top == "git":
        return "git-checkout"
    if kind == "f" and (head == SQLITE_MAGIC or parts[-1].endswith("-wal")):
        return "sqlite"
    if top in (".codex", ".claude", ".claude.json"):
        return "agents"
    if top == ".ssh" or parts[:2] == [".config", "agent"]:
        return "credentials"
    if "node_modules" in parts:
        return "node-modules"
    if top == "projects":
        return "projects"
    if top == ".cache":
        return "cache"
    if top == "data":
        return "large-data"
    if top.startswith(".") or top == "dotfiles":
        return "dotfiles"
    return "edge"


def host_markers(root: str) -> tuple[bytes, ...]:
    """Host paths that must never appear in the corpus, longest first.

    The corpus root and DEST, $HOME as given and resolved, the generator's
    checkout, the temp directory and the git scratch prefix. Root-normalised
    files are scanned after the root is replaced, so a marker that prefixes
    the root (a DEST under $HOME or $TMPDIR) only matches a real leak.
    """
    home = os.path.expanduser("~")
    temp = tempfile.gettempdir()
    found = {
        root,
        os.path.dirname(root),
        home,
        os.path.realpath(home),
        str(HERE.parents[3]),
        temp,
        os.path.realpath(temp),
        SCRATCH_PREFIX,
    }
    markers = {os.fsencode(m) for m in found if len(m) >= HOST_MARKER_MIN}
    return tuple(sorted(markers, key=lambda m: (-len(m), m)))


def norm_kind(parts: list[str]) -> str:
    """Which normalisation a regular file gets (see the module docstring)."""
    if parts[-1] == ".git":
        return "root"
    admin = len(parts) >= 4 and parts[-3] == "worktrees" and is_gitdir_name(parts[-4])
    if parts[-1] == "gitdir" and admin:
        return "root"
    if parts[-1] == "index" and (
        admin or (len(parts) >= 2 and is_gitdir_name(parts[-2]))
    ):
        return "git-index"
    return "raw"


def digest_file(path: Path) -> tuple[int, str, bytes]:
    h = hashlib.shake_256()
    size = 0
    head = b""
    with path.open("rb") as handle:
        while chunk := handle.read(BLOCK):
            if not head:
                head = chunk[:16]
            h.update(chunk)
            size += len(chunk)
    return size, h.hexdigest(32), head


def manifest(
    corpus: Path, root: str, allow_shm: bool = True
) -> tuple[str, list[str], dict]:
    """The canonical manifest of `corpus`, its problems and its counts.

    Every regular file up to LEAK_SCAN_LIMIT, and every symlink target, is
    scanned for host paths (`host_markers`, the corpus root first). A
    root-normalised file is scanned after the root is replaced, which is the
    one documented exception; one that already holds the token is a problem.
    A hit is a problem. A `-shm` beside a SQLite database that is not exempt
    (`sealed_walk`; never on a sealed copy, `allow_shm` false) stays in the
    manifest and is a problem. counts["classes"] holds per-class entries,
    dirs, files, symlinks and bytes (`entry_class`).
    """
    root_bytes = os.fsencode(root)
    markers = host_markers(root)
    problems: list[str] = []
    classes = {
        name: dict.fromkeys(("entries", "dirs", "files", "symlinks", "bytes"), 0)
        for name in CLASSES
    }

    def scan(rel: str, data: bytes) -> None:
        for marker in markers:
            if marker in data:
                where = esc(os.fsdecode(marker))
                problems.append(f"host path {where} inside {esc(rel)}")
                return

    counts: dict = dict.fromkeys(
        (
            "entries",
            "dirs",
            "files",
            "symlinks",
            "bytes",
            "empty_dirs",
            "git_dirs",
            "bare_repos",
            "worktree_admins",
            "gitfiles",
            "git_indexes",
            "loose_objects",
            "packs",
            "jsonl",
            "jsonl_zst",
            "sqlite",
            "sqlite_wal",
            "large_files",
            "small_files",
            "sqlite_shm_ignored",
            "host_scan_skipped",
        ),
        0,
    )
    entries, shm = sealed_walk(corpus, allow_shm)
    counts["sqlite_shm_ignored"] = len(shm)
    for rel, info in entries:
        if stat.S_ISREG(info.st_mode) and beside_sqlite(corpus, rel):
            why = wal_index_problem(corpus, rel) if allow_shm else "a sealed copy"
            problems.append(f"SQLite -shm {esc(rel)} is not exempt: {why}")
    children: dict[str, int] = {}
    for rel, _info in entries:
        parent = rel.rpartition("/")[0]
        children[parent] = children.get(parent, 0) + 1
    lines = [MANIFEST_HEADER]
    for rel, info in entries:
        parts = rel.split("/")
        in_git = any(is_gitdir_name(p) for p in parts[:-1])
        mode = info.st_mode
        head = b""
        size = 0
        if stat.S_ISDIR(mode):
            kind = "d"
            counts["dirs"] += 1
            counts["empty_dirs"] += children.get(rel, 0) == 0
            counts["git_dirs"] += parts[-1] == ".git"
            counts["bare_repos"] += parts[-1].endswith(".git") and parts[-1] != ".git"
            counts["worktree_admins"] += (
                len(parts) >= 3
                and parts[-2] == "worktrees"
                and parts[-3].endswith(".git")
            )
            row = (rel, "d", f"{mode & 0o7777:04o}", "-", "-", "-", "-")
        elif stat.S_ISLNK(mode):
            kind = "l"
            counts["symlinks"] += 1
            target = os.readlink(corpus / rel)
            scan(rel, os.fsencode(target))
            row = (rel, "l", "-", str(len(os.fsencode(target))), "-", esc(target), "-")
        elif stat.S_ISREG(mode):
            kind = "f"
            counts["files"] += 1
            norm = norm_kind(parts)
            path = corpus / rel
            if norm == "raw" and info.st_size > LEAK_SCAN_LIMIT:
                size, digest, head = digest_file(path)
                counts["host_scan_skipped"] += 1
            else:
                data = path.read_bytes()
                head = data[:16]
                size = len(data)
                if norm == "root":
                    if ROOT_TOKEN in data:
                        problems.append(
                            f"{esc(rel)} already holds {ROOT_TOKEN.decode()}"
                        )
                    data = data.replace(root_bytes, ROOT_TOKEN)
                    size = len(data)
                    counts["gitfiles"] += parts[-1] == ".git"
                scan(rel, data)
                if norm == "git-index":
                    counts["git_indexes"] += 1
                    try:
                        data = index_logical(data)
                    except (CorpusError, ValueError, struct.error) as err:
                        problems.append(f"index {esc(rel)}: {err}")
                digest = hashlib.shake_256(data).hexdigest(32)
            name = parts[-1]
            counts["bytes"] += size
            counts["loose_objects"] += (
                in_git
                and len(parts) >= 3
                and parts[-3] == "objects"
                and len(parts[-2]) == 2
                and len(name) == 38
            )
            counts["packs"] += in_git and name.endswith(".pack")
            counts["jsonl"] += name.endswith(".jsonl")
            counts["jsonl_zst"] += name.endswith(".jsonl.zst")
            counts["sqlite"] += head == SQLITE_MAGIC
            counts["sqlite_wal"] += name.endswith("-wal")
            counts["large_files"] += info.st_size >= MIB
            counts["small_files"] += info.st_size <= 4 * KIB
            row = (rel, "f", f"{mode & 0o7777:04o}", str(size), digest, "-", norm)
        else:
            problems.append(f"not a file, directory or symlink: {esc(rel)}")
            continue
        counts["entries"] += 1
        bucket = classes[entry_class(parts, kind, head)]
        bucket["entries"] += 1
        bucket[{"d": "dirs", "f": "files", "l": "symlinks"}[kind]] += 1
        bucket["bytes"] += size
        lines.append("\t".join((esc(row[0]), *row[1:])) + "\n")
    counts["classes"] = classes
    return "".join(lines), problems, counts


def identity_of(text: str) -> str:
    return hashlib.shake_256(text.encode()).hexdigest(32)


def rows_of(text: str) -> dict[str, list[str]]:
    # Split on newline only: str.splitlines also splits on U+2028 and the
    # like, which esc() leaves in a path.
    rows = {}
    for line in text.split("\n")[1:]:
        if line:
            fields = line.split("\t")
            rows[fields[0]] = fields
    return rows


def diff_rows(
    before: dict[str, list[str]], after: dict[str, list[str]]
) -> tuple[list[str], list[str], list[str]]:
    def order(paths: Iterable[str]) -> list[str]:
        return sorted(paths, key=str.encode)

    added = order(after.keys() - before.keys())
    removed = order(before.keys() - after.keys())
    modified = order(p for p in before.keys() & after.keys() if before[p] != after[p])
    return added, removed, modified


# ---- generate, verify and seal -----------------------------------------------------


def toolchain() -> dict[str, str | None]:
    def out(args: list[str]) -> str:
        try:
            return subprocess.run(args, capture_output=True, text=True).stdout
        except OSError:
            return ""

    git = out(["git", "--version"]).split()
    zlib = [
        line.strip()
        for line in out(["git", "version", "--build-options"]).splitlines()
        if line.strip().startswith("zlib")
    ]
    zstd = (
        re.search(r"v(\d+\.\d+\.\d+)", out(["zstd", "-V"]))
        if shutil.which("zstd")
        else None
    )
    return {
        "git": git[-1] if git else None,
        "git_zlib": zlib[0] if zlib else None,
        "sqlite": sqlite3.sqlite_version,
        "zstd": zstd.group(1) if zstd else None,
        "python": platform.python_version(),
    }


def git_version(text: str | None) -> tuple[int, int]:
    match = re.match(r"(\d+)\.(\d+)", text or "")
    return (int(match.group(1)), int(match.group(2))) if match else (0, 0)


def recorded_identity(scale: str, seed: str, tools: dict) -> str | None:
    """The recorded identity for (scale, seed), if this toolchain recorded it."""
    entry = RECORDED.get((scale, seed))
    if entry and all(tools.get(key) == value for key, value in entry[1].items()):
        return entry[0]
    return None


def write_json(path: Path, value: object) -> None:
    path.write_text(
        json.dumps(value, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )


def readme(seal: dict) -> str:
    counts = seal["counts"]
    text = (
        f"# Estate-shaped corpus v1 ({seal['identity'][:16]})\n\n"
        "Generated by bulkload `crates/bulkload-bench/scripts/estate_corpus.py`\n"
        f"(WP0(e), OI-1003-Q19) with seed `{seal['seed']}` and scale "
        f"`{seal['scale']}`.\n\n"
        f"- Identity (SHAKE-256/256 of MANIFEST.tsv): `{seal['identity']}`\n"
        f"- {counts['entries']:,} entries, {counts['files']:,} files, "
        f"{counts['bytes']:,} bytes under `corpus/`.\n"
        "- Check before use: `estate_corpus.py verify <this dir>`.\n"
        "- Not relocatable: linked worktrees point at the absolute generation path,\n"
        "  so never run git in a moved copy.\n"
    )
    sealed = seal.get("readonly")
    if sealed:
        text += (
            "\n## PROTECTED: sealed read-only\n\n"
            "Do not modify, move, prune or delete this directory. It was sealed in\n"
            f"place on {sealed['sealed_at']} ({READONLY_MODES}).\n"
            f"`verify` checks it against `{RECEIPT}`, so any change fails,\n"
            "a `mutate` round included.\n\n"
            f"- Read-only view identity: `{sealed['identity']}`\n"
        )
    return text


def generate(dest: Path, seed: str, scale_name: str) -> tuple[int, str | None]:
    os.umask(UMASK)
    if dest.exists() or not dest.parent.is_dir():
        print(
            f"estate-corpus refused: DEST must be new under an existing parent: {dest}"
        )
        return 2, None
    if default_acl(dest.parent):
        print(
            "estate-corpus refused: DEST's parent has a default ACL, which "
            f"overrides umask 022 for every corpus entry: {dest.parent}"
        )
        return 2, None
    tools = toolchain()
    if git_version(tools["git"]) < MIN_GIT:
        print(f"estate-corpus refused: git >= 2.45 required, found {tools['git']}")
        return 2, None
    started = time.monotonic()
    scale = SCALES[scale_name]
    base = f"{seed}/{scale_name}"
    corpus = dest / "corpus"
    for top in (dest, corpus):
        top.mkdir()
        top.chmod(0o755)  # an explicit mode drops a setgid bit from the parent
    root = os.path.realpath(corpus)
    notes: list[str] = []
    repos = []
    with tempfile.TemporaryDirectory(prefix=SCRATCH_PREFIX) as raw:
        scratch = Path(raw)
        build_home(Path(root), base)
        build_large(Path(root), base, scale)
        build_cache(Path(root), base, scale)
        build_node(Path(root), base, scale)
        build_agents(Path(root), base, scale, scratch, notes)
        g = Git(scratch, Path(root), HISTORY_EPOCH)
        for i in range(scale.repos):
            repos.append(build_repo(g, Path(root), base, scale, i))
        repos.append(build_history(g, Path(root), base, scale))
    fixed = canonical_modes(Path(root))
    if fixed:
        notes.append(
            f"canonical_modes cleared special or group/other write bits on {fixed}"
        )
    text, problems, counts = manifest(Path(root), root)
    identity = identity_of(text)
    recorded = recorded_identity(scale_name, seed, tools)
    if recorded and recorded != identity:
        problems.append(f"identity differs from the recorded {recorded}")
    seal = {
        "format": FORMAT,
        "seed": seed,
        "scale": scale_name,
        "identity": identity,
        "base_identity": identity,
        "identity_algorithm": "SHAKE-256/256 of MANIFEST.tsv",
        "root": root,
        "counts": counts,
        "repos": repos,
        "tools": tools,
        "notes": notes,
        "generator": "crates/bulkload-bench/scripts/estate_corpus.py",
        "generator_shake256": hashlib.shake_256(HERE.read_bytes()).hexdigest(32),
        "mutations": [],
    }
    (dest / "MANIFEST.tsv").write_text(text, encoding="utf-8")
    write_json(dest / "SEAL.json", seal)
    (dest / "README.md").write_text(readme(seal), encoding="utf-8")
    for problem in problems:
        print(f"estate-corpus problem: {problem}")
    print(
        f"estate-corpus generated={corpus} scale={scale_name} seed={seed} "
        f"entries={counts['entries']} files={counts['files']} dirs={counts['dirs']} "
        f"symlinks={counts['symlinks']} bytes={counts['bytes']} "
        f"seconds={time.monotonic() - started:.1f} identity={identity} "
        f"recorded={'none' if recorded is None else recorded == identity}"
    )
    return (1 if problems else 0), identity


def load_json(path: Path) -> dict | None:
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    return value if isinstance(value, dict) else None


def load_seal(dest: Path) -> dict | None:
    return load_json(dest / "SEAL.json")


def is_sealed(dest: Path, seal: dict) -> bool:
    """Whether `seal` sealed DEST; its receipt then pins DEST for good."""
    return bool(seal.get("readonly")) or os.path.lexists(dest / RECEIPT)


def readonly_mode(kind: str, mode: str) -> str:
    """The mode column of an entry once sealed (READONLY_MODES)."""
    if kind == "d":
        return "0555"
    if kind == "f":
        return "0555" if int(mode, 8) & 0o111 else "0444"
    return mode


def readonly_view(text: str) -> str:
    """A manifest with every mode mapped to its sealed, read-only mode."""
    head, _, body = text.partition("\n")
    out = [head + "\n"]
    for line in body.split("\n"):
        if line:
            fields = line.split("\t")
            fields[2] = readonly_mode(fields[1], fields[2])
            out.append("\t".join(fields) + "\n")
    return "".join(out)


def writable_count(dest: Path, text: str) -> int:
    """Entries of a sealed DEST that are not at their read-only mode.

    Corpus entries come from the manifest `text`; DEST itself, the corpus
    root, DEST's top-level files and the mutation sidecars must have no write
    bit.
    """
    view = readonly_view(text)
    count = sum(a != b for a, b in zip(text.split("\n"), view.split("\n")))
    paths = [dest, dest / "corpus"]
    with os.scandir(dest) as top:
        for entry in top:
            if entry.name == "corpus":
                continue
            paths.append(Path(entry.path))
            if entry.is_dir(follow_symlinks=False):
                with os.scandir(entry.path) as inner:
                    paths += [Path(e.path) for e in inner]
    return count + sum(bool(os.lstat(p).st_mode & 0o222) for p in paths)


def verify(dest: Path) -> int:
    seal = load_seal(dest)
    corpus = dest / "corpus"
    if seal is None or not corpus.is_dir():
        print(f"estate-corpus verify dest={dest} missing=1 ok=False")
        return 1
    sealed = is_sealed(dest, seal)
    # No reader can create a -shm in a sealed (0555) copy, so none is exempt.
    text, problems, counts = manifest(corpus, seal["root"], allow_shm=not sealed)
    for problem in problems:
        print(f"estate-corpus problem: {problem}")
    if counts["sqlite_shm_ignored"]:
        for rel in sealed_walk(corpus)[1]:
            print(f"estate-corpus note: unsealed SQLite wal-index {esc(rel)}")
    path = dest / "MANIFEST.tsv"
    recorded = path.read_text(encoding="utf-8") if path.is_file() else None
    if sealed:
        receipt = load_json(dest / RECEIPT) or {}
        expected = receipt.get("readonly_identity")
        current = readonly_view(text)
        identity = identity_of(current)
        baseline = readonly_view(recorded) if recorded is not None else None
        checks = {
            "receipt": expected is not None
            and expected == (seal.get("readonly") or {}).get("identity"),
            "manifest": recorded is not None
            and identity_of(recorded) == receipt.get("identity") == seal["identity"],
            "no-round-since-seal": len(seal["mutations"]) == receipt.get("mutations"),
            "identity": identity == expected,
            "read-only": writable_count(dest, text) == 0,
        }
        for name, passed in checks.items():
            if not passed:
                print(f"estate-corpus sealed check failed: {name}")
        ok = not problems and all(checks.values())
    else:
        expected = seal["identity"]
        current = text
        identity = identity_of(text)
        baseline = recorded
        ok = not problems and identity == expected
    if not ok and baseline is not None:
        added, removed, modified = diff_rows(rows_of(baseline), rows_of(current))
        for sign, paths in (("+", added), ("-", removed), ("~", modified)):
            for rel in paths[:20]:
                print(f"estate-corpus differs: {sign} {rel}")
    relocated = os.path.realpath(corpus) != seal["root"]
    print(
        f"estate-corpus verify dest={dest} identity={identity} "
        f"expected={expected} sealed={int(sealed)} relocated={int(relocated)} "
        f"shm_ignored={counts['sqlite_shm_ignored']} ok={ok}"
    )
    return 0 if ok else 1


def seal_dest(dest: Path) -> int:
    """Make DEST read-only in place and write its verify receipt (see Seal)."""
    os.umask(UMASK)
    started = time.monotonic()
    seal = load_seal(dest)
    corpus = dest / "corpus"
    if seal is None or not corpus.is_dir():
        print(f"estate-corpus refused: seal needs a generated DEST: {dest}")
        return 2
    if is_sealed(dest, seal):
        print(f"estate-corpus refused: DEST is already sealed: {dest}")
        return 2
    root = seal["root"]
    if os.path.realpath(corpus) != root:
        print(f"estate-corpus refused: seal runs in place only (generated at {root})")
        return 2
    text, problems, counts = manifest(corpus, root)
    if counts["sqlite_shm_ignored"]:
        print("estate-corpus refused: a SQLite wal-index (-shm) is present")
        return 2
    path = dest / "MANIFEST.tsv"
    recorded = path.read_text(encoding="utf-8") if path.is_file() else None
    if problems or text != recorded or identity_of(text) != seal["identity"]:
        for problem in problems:
            print(f"estate-corpus problem: {problem}")
        print("estate-corpus refused: the corpus does not match its seal")
        return 1
    view = readonly_view(text)
    readonly_identity = identity_of(view)
    for rel, info in walk(corpus):
        if not stat.S_ISLNK(info.st_mode):
            kind = "d" if stat.S_ISDIR(info.st_mode) else "f"
            mode = readonly_mode(kind, f"{info.st_mode & 0o7777:04o}")
            os.chmod(corpus / rel, int(mode, 8))
    corpus.chmod(0o555)
    sealed_text, problems, counts = manifest(corpus, root, allow_shm=False)
    for problem in problems:
        print(f"estate-corpus problem: {problem}")
    if problems or sealed_text != view:
        print("estate-corpus seal failed: the sealed tree is not the read-only view")
        return 1
    sealed_at = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    receipt = {
        "format": RECEIPT_FORMAT,
        "rulings": RULINGS,
        "dest": str(dest),
        "root": root,
        "seed": seal["seed"],
        "scale": seal["scale"],
        "identity": seal["identity"],
        "base_identity": seal["base_identity"],
        "readonly_identity": readonly_identity,
        "readonly_modes": READONLY_MODES,
        "mutations": len(seal["mutations"]),
        "verified": {
            "ok": True,
            "check": "sealed tree == read-only view of MANIFEST.tsv",
            "problems": 0,
            "shm_ignored": 0,
            "host_scan_skipped": counts["host_scan_skipped"],
            "seconds": round(time.monotonic() - started, 1),
        },
        "counts": counts,
        "tools": toolchain(),
        "generator_shake256": seal["generator_shake256"],
        "sealer_shake256": hashlib.shake_256(HERE.read_bytes()).hexdigest(32),
        "host": platform.node(),
        "sealed_at": sealed_at,
    }
    seal["readonly"] = {
        "identity": readonly_identity,
        "modes": READONLY_MODES,
        "receipt": RECEIPT,
        "sealed_at": sealed_at,
    }
    write_json(dest / "SEAL.json", seal)
    write_json(dest / RECEIPT, receipt)
    (dest / "README.md").write_text(readme(seal), encoding="utf-8")
    for dirpath, dirnames, filenames in os.walk(dest):
        if Path(dirpath) == dest:
            dirnames[:] = [d for d in dirnames if d != "corpus"]
        for name in filenames:
            if not os.path.islink(Path(dirpath) / name):
                os.chmod(Path(dirpath) / name, 0o444)
        os.chmod(dirpath, 0o555)
    print(
        f"estate-corpus sealed={dest} identity={seal['identity']} "
        f"readonly_identity={readonly_identity} receipt={dest / RECEIPT} "
        f"seconds={time.monotonic() - started:.1f}"
    )
    return 0


# ---- S2 stat snapshot ----------------------------------------------------------------


def s2_rows(corpus: Path) -> dict[str, list[str]]:
    """Every entry's stat identity: the corpus root (`.`) and any -shm included."""
    rows = {}
    for rel, info in [(".", os.lstat(corpus)), *walk(corpus)]:
        mode = info.st_mode
        kind = (
            "d" if stat.S_ISDIR(mode)
            else "l" if stat.S_ISLNK(mode)
            else "f" if stat.S_ISREG(mode)
            else "o"
        )  # fmt: skip
        fields = [
            esc(rel), kind, f"{stat.S_IMODE(mode):04o}", str(info.st_ino),
            str(info.st_size), str(info.st_mtime_ns), str(info.st_ctime_ns),
        ]  # fmt: skip
        rows[fields[0]] = fields
    return rows


def s2_snapshot(dest: Path, out: Path) -> int:
    """Record every entry's stat identity before a measured pass (S2)."""
    corpus = dest / "corpus"
    real = os.path.realpath(corpus)
    target = os.path.realpath(out)
    if not corpus.is_dir() or out.exists() or (target + "/").startswith(real + "/"):
        print(
            "estate-corpus refused: s2-snapshot needs DEST/corpus and a new OUT "
            f"outside it: {dest} {out}"
        )
        return 2
    rows = s2_rows(corpus)
    lines = "".join("\t".join(row) + "\n" for row in rows.values())
    out.write_text(S2_HEADER + lines, encoding="utf-8")
    print(f"estate-corpus s2-snapshot dest={dest} entries={len(rows)} out={out}")
    return 0


def s2_diff(dest: Path, snapshot: Path) -> int:
    """Every stat change since `snapshot`; exit 0 only if there is none.

    `verify` cannot see a write that leaves the manifest as it was: an index
    refreshed under index.lock, a rewrite with the same bytes, a touch, or a
    -shm. This sees each of them, and nothing a read changes (atime is not
    recorded).
    """
    corpus = dest / "corpus"
    try:
        text = snapshot.read_text(encoding="utf-8")
    except OSError:
        text = ""
    if not text.startswith(S2_HEADER) or not corpus.is_dir():
        print(
            f"estate-corpus refused: s2-diff needs DEST/corpus and a snapshot: {dest}"
        )
        return 2
    before = rows_of(text)
    after = s2_rows(corpus)
    added, removed, modified = diff_rows(before, after)
    for sign, paths in (("+", added), ("-", removed)):
        for rel in paths:
            print(f"estate-corpus s2: {sign} {rel}")
    for rel in modified:
        moved = [n for n, a, b in zip(S2_FIELDS, before[rel], after[rel]) if a != b]
        print(f"estate-corpus s2: ~ {rel} {','.join(moved)}")
    ok = not (added or removed or modified)
    print(
        f"estate-corpus s2-diff dest={dest} added={len(added)} removed={len(removed)} "
        f"changed={len(modified)} ok={ok}"
    )
    return 0 if ok else 1


