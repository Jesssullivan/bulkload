def selftest() -> int:
    """Generate scale=small twice, verify, mutate and tamper (optional tier)."""
    started = time.monotonic()
    temps = [
        Path(tempfile.mkdtemp(prefix=f"estate-corpus-selftest-{n}-")) for n in "ab"
    ]
    failures: list[str] = []

    def check(ok: bool, what: str) -> None:
        print(f"estate-corpus selftest {'ok' if ok else 'FAIL'}: {what}")
        if not ok:
            failures.append(what)

    try:
        a, b = (t / "dest" for t in temps)
        rc_a, id_a = generate(a, DEFAULT_SEED, "small")
        rc_b, id_b = generate(b, DEFAULT_SEED, "small")
        check(rc_a == 0 and rc_b == 0, "both generations are clean")
        check(id_a == id_b, f"two generations share one identity ({id_a})")
        check(
            (a / "MANIFEST.tsv").read_bytes() == (b / "MANIFEST.tsv").read_bytes(),
            "the two manifests are byte-identical",
        )
        tools = load_seal(a)["tools"]
        recorded = recorded_identity("small", DEFAULT_SEED, tools)
        if recorded:
            check(id_a == recorded, f"identity equals the recorded {recorded[:16]}")
        else:
            print(f"estate-corpus selftest note: nothing recorded for tools {tools}")
        check(verify(a) == 0, "verify accepts the sealed corpus")
        before = rows_of((a / "MANIFEST.tsv").read_text())
        check(mutate(a, len(KINDS)) == 0, "mutate applies one of each operation")
        check(mutate(b, len(KINDS)) == 0, "mutate applies to the second copy")
        side = json.loads((a / "mutations/round-0001.json").read_text())
        twin = json.loads((b / "mutations/round-0001.json").read_text())
        after = rows_of((a / "MANIFEST.tsv").read_text())
        added, removed, modified = diff_rows(before, after)
        check(
            side["identity_after"] != side["identity_before"],
            "mutation changes the identity",
        )
        check(
            side["identity_after"] == twin["identity_after"],
            "mutation is deterministic",
        )
        check(
            side["changed"]
            == {"added": added, "removed": removed, "modified": modified},
            "the sidecar lists exactly the manifest difference",
        )
        check(
            {op["kind"] for op in side["operations"]} == set(KINDS), "all six kinds ran"
        )
        changed = {*added, *removed, *modified}
        check(
            all(op["path"] in changed for op in side["operations"]),
            "every operation's path is in the difference",
        )
        content = {p for p in (*added, *modified) if after[p][1] == "f"}
        check(
            content <= set(side["reads_allowed"]),
            "reads_allowed covers every changed file",
        )
        check(verify(a) == 0, "verify accepts the mutated corpus against its new seal")
        victim = b / "corpus" / "names" / "with space.txt"
        with victim.open("ab") as handle:
            handle.write(b"!")
        check(verify(b) == 1, "verify rejects a tampered byte")
    except (
        CorpusError,
        OSError,
        KeyError,
        ValueError,
        subprocess.SubprocessError,
    ) as err:
        check(False, f"self-test raised {type(err).__name__}: {err}")
    finally:
        for temp in temps:
            shutil.rmtree(temp, ignore_errors=True)
        check(not any(t.exists() for t in temps), "temporary corpora removed")
    print(
        f"estate-corpus selftest failures={len(failures)} "
        f"seconds={time.monotonic() - started:.1f} ok={not failures}"
    )
    return 1 if failures else 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="command", required=True)
    gen = sub.add_parser("generate", help="build a new corpus under DEST")
    gen.add_argument("dest")
    gen.add_argument("--seed", default=DEFAULT_SEED)
    gen.add_argument("--scale", choices=sorted(SCALES), default="small")
    ver = sub.add_parser("verify", help="check DEST/corpus against DEST/SEAL.json")
    ver.add_argument("dest")
    man = sub.add_parser("manifest", help="print the canonical manifest")
    man.add_argument("corpus")
    man.add_argument("--root", help="corpus root to normalise (default: CORPUS)")
    mut = sub.add_parser("mutate", help="the S3 knob: apply N changes in place")
    mut.add_argument("dest")
    mut.add_argument("count", metavar="N", type=int)
    sub.add_parser("selftest", help="optional-tier round trip at scale small")
    args = parser.parse_args(argv)
    try:
        if args.command == "generate":
            return generate(Path(args.dest).absolute(), args.seed, args.scale)[0]
        if args.command == "verify":
            return verify(Path(args.dest).absolute())
        if args.command == "mutate":
            return mutate(Path(args.dest).absolute(), args.count)
        if args.command == "selftest":
            return selftest()
        corpus = Path(args.corpus).absolute()
        text, problems, _ = manifest(corpus, args.root or os.path.realpath(corpus))
        sys.stdout.write(text)
        print(f"identity={identity_of(text)} problems={problems}", file=sys.stderr)
        return 1 if problems else 0
    except CorpusError as err:
        print(f"estate-corpus failed: {err}")
        return 1


if __name__ == "__main__":
    sys.exit(main())
