def esc(text: str) -> str:
    out = []
    for ch in text:
        o = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif 0xDC80 <= o <= 0xDCFF:
            out.append(f"\\x{o & 0xFF:02x}")
        elif o < 0x20 or o == 0x7F:
            out.append(f"\\x{o:02x}")
        else:
            out.append(ch)
    return "".join(out)


def walk(corpus: Path) -> list[tuple[str, os.stat_result]]:
    out = []
    stack = [""]
    while stack:
        rel = stack.pop()
        with os.scandir(corpus / rel if rel else corpus) as entries:
            for entry in entries:
                child = f"{rel}/{entry.name}" if rel else entry.name
                info = entry.stat(follow_symlinks=False)
                out.append((child, info))
                if stat.S_ISDIR(info.st_mode):
                    stack.append(child)
    out.sort(key=lambda row: os.fsencode(row[0]))
    return out


def index_logical(data: bytes) -> bytes:
    """A git index without its stat words and trailing checksum."""
    if data[:4] != b"DIRC":
        raise CorpusError("not a DIRC index")
    version, count = struct.unpack(">II", data[4:12])
    if version not in (2, 3):
        raise CorpusError(f"index version {version}")
    out = bytearray(data[:12])
    pos = 12
    for _ in range(count):
        mode = struct.unpack_from(">I", data, pos + 24)[0]
        out += struct.pack(">10I", 0, 0, 0, 0, 0, 0, mode, 0, 0, 0)
        flags = struct.unpack_from(">H", data, pos + 60)[0]
        name = pos + (64 if flags & 0x4000 else 62)
        # On disk an entry is padded with 1-8 NULs to a multiple of 8 bytes.
        size = (data.index(b"\0", name) - pos + 8) & ~7
        out += data[pos + 40 : pos + size]
        pos += size
    extensions = pos
    tail = len(data) - 20
    while pos < tail:
        sig = data[pos : pos + 4]
        if sig in (b"UNTR", b"FSMN", b"link"):
            raise CorpusError(f"stat-bearing index extension {sig.decode()}")
        pos += 8 + struct.unpack_from(">I", data, pos + 4)[0]
    if pos != tail:
        raise CorpusError("index extensions overrun")
    return bytes(out + data[extensions:tail])


def is_gitdir_name(name: str) -> bool:
    return name == ".git" or name.endswith(".git")


def norm_kind(parts: list[str]) -> str:
    """Which normalisation a regular file gets (see the module docstring)."""
    if parts[-1] == ".git":
        return "root"
    admin = len(parts) >= 4 and parts[-3] == "worktrees" and is_gitdir_name(parts[-4])
    if parts[-1] == "gitdir" and admin:
        return "root"
    if parts[-1] == "index" and (
        admin or (len(parts) >= 2 and is_gitdir_name(parts[-2]))
    ):
        return "git-index"
    return "raw"


def digest_file(path: Path) -> tuple[int, str, bytes]:
    h = hashlib.shake_256()
    size = 0
    head = b""
    with path.open("rb") as handle:
        while chunk := handle.read(BLOCK):
            if not head:
                head = chunk[:16]
            h.update(chunk)
            size += len(chunk)
    return size, h.hexdigest(32), head


def manifest(corpus: Path, root: str) -> tuple[str, list[str], dict[str, int]]:
    """The canonical manifest of `corpus`, its problems and its counts."""
    root_bytes = os.fsencode(root)
    problems: list[str] = []
    counts = dict.fromkeys(
        (
            "entries",
            "dirs",
            "files",
            "symlinks",
            "bytes",
            "empty_dirs",
            "git_dirs",
            "bare_repos",
            "worktree_admins",
            "gitfiles",
            "git_indexes",
            "loose_objects",
            "packs",
            "jsonl",
            "jsonl_zst",
            "sqlite",
            "sqlite_wal",
            "large_files",
            "small_files",
        ),
        0,
    )
    entries = walk(corpus)
    children: dict[str, int] = {}
    for rel, _info in entries:
        parent = rel.rpartition("/")[0]
        children[parent] = children.get(parent, 0) + 1
    lines = [MANIFEST_HEADER]
    for rel, info in entries:
        parts = rel.split("/")
        in_git = any(is_gitdir_name(p) for p in parts[:-1])
        mode = info.st_mode
        counts["entries"] += 1
        if stat.S_ISDIR(mode):
            counts["dirs"] += 1
            counts["empty_dirs"] += children.get(rel, 0) == 0
            counts["git_dirs"] += parts[-1] == ".git"
            counts["bare_repos"] += parts[-1].endswith(".git") and parts[-1] != ".git"
            counts["worktree_admins"] += (
                len(parts) >= 3
                and parts[-2] == "worktrees"
                and parts[-3].endswith(".git")
            )
            row = (rel, "d", f"{mode & 0o7777:04o}", "-", "-", "-", "-")
        elif stat.S_ISLNK(mode):
            counts["symlinks"] += 1
            target = os.readlink(corpus / rel)
            size = str(len(os.fsencode(target)))
            row = (rel, "l", "-", size, "-", esc(target), "-")
        elif stat.S_ISREG(mode):
            counts["files"] += 1
            norm = norm_kind(parts)
            path = corpus / rel
            if norm == "raw" and not (in_git and info.st_size <= LEAK_SCAN_LIMIT):
                size, digest, head = digest_file(path)
            else:
                data = path.read_bytes()
                head = data[:16]
                size = len(data)
                if norm == "raw" and root_bytes in data:
                    problems.append(f"absolute corpus root inside {rel}")
                elif norm == "root":
                    data = data.replace(root_bytes, ROOT_TOKEN)
                    size = len(data)
                    counts["gitfiles"] += parts[-1] == ".git"
                elif norm == "git-index":
                    counts["git_indexes"] += 1
                    try:
                        data = index_logical(data)
                    except (CorpusError, ValueError, struct.error) as err:
                        problems.append(f"index {rel}: {err}")
                digest = hashlib.shake_256(data).hexdigest(32)
            name = parts[-1]
            counts["bytes"] += size
            counts["loose_objects"] += (
                in_git
                and len(parts) >= 3
                and parts[-3] == "objects"
                and len(parts[-2]) == 2
                and len(name) == 38
            )
            counts["packs"] += in_git and name.endswith(".pack")
            counts["jsonl"] += name.endswith(".jsonl")
            counts["jsonl_zst"] += name.endswith(".jsonl.zst")
            counts["sqlite"] += head == b"SQLite format 3\0"
            counts["sqlite_wal"] += name.endswith("-wal")
            counts["large_files"] += info.st_size >= MIB
            counts["small_files"] += info.st_size <= 4 * KIB
            row = (rel, "f", f"{mode & 0o7777:04o}", str(size), digest, "-", norm)
        else:
            problems.append(f"not a file, directory or symlink: {rel}")
            continue
        lines.append("\t".join((esc(row[0]), *row[1:])) + "\n")
    return "".join(lines), problems, counts


def identity_of(text: str) -> str:
    return hashlib.shake_256(text.encode()).hexdigest(32)


def rows_of(text: str) -> dict[str, list[str]]:
    rows = {}
    for line in text.splitlines()[1:]:
        fields = line.split("\t")
        rows[fields[0]] = fields
    return rows


def diff_rows(
    before: dict[str, list[str]], after: dict[str, list[str]]
) -> tuple[list[str], list[str], list[str]]:
    def order(paths: Iterable[str]) -> list[str]:
        return sorted(paths, key=str.encode)

    added = order(after.keys() - before.keys())
    removed = order(before.keys() - after.keys())
    modified = order(p for p in before.keys() & after.keys() if before[p] != after[p])
    return added, removed, modified


