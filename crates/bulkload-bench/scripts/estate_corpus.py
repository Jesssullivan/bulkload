# ---- deterministic bytes ---------------------------------------------------


def shake(label: str, size: int) -> bytes:
    return hashlib.shake_256(label.encode()).digest(size)


class Det:
    """A SHAKE-256 stream keyed by a label; the same on every Python."""

    def __init__(self, label: str) -> None:
        self.label = label
        self._buf = b""
        self._pos = 0
        self._block = 0

    def take(self, size: int) -> bytes:
        while len(self._buf) - self._pos < size:
            fresh = shake(f"{self.label}#{self._block}", 4096)
            self._buf = self._buf[self._pos :] + fresh
            self._pos = 0
            self._block += 1
        out = self._buf[self._pos : self._pos + size]
        self._pos += size
        return out

    def below(self, bound: int) -> int:
        if bound <= 0:
            raise ValueError("bound must be positive")
        limit = (1 << 64) - (1 << 64) % bound
        while True:
            value = int.from_bytes(self.take(8), "big")
            if value < limit:
                return value % bound

    def between(self, low: int, high: int) -> int:
        return low + self.below(high - low + 1)

    def choice(self, items: list[str] | tuple[str, ...]) -> str:
        return items[self.below(len(items))]

    def chance(self, one_in: int) -> bool:
        return self.below(one_in) == 0

    def shuffled(self, items: Iterable[str]) -> list[str]:
        out = list(items)
        for i in range(len(out) - 1, 0, -1):
            j = self.below(i + 1)
            out[i], out[j] = out[j], out[i]
        return out

    def word(self) -> str:
        return WORDS[self.below(len(WORDS))]

    def hex(self, size: int) -> str:
        return self.take(size).hex()

    def uuid(self) -> str:
        h = self.hex(16)
        return f"{h[:8]}-{h[8:12]}-4{h[13:16]}-a{h[17:20]}-{h[20:32]}"


def stream(label: str, size: int) -> Iterator[bytes]:
    """r23_corpus.py's counter mode: block i is SHAKE-256(label/i)."""
    index = 0
    while size > 0:
        block = shake(f"{label}/{index}", min(size, BLOCK))
        yield block
        size -= len(block)
        index += 1


def blob(label: str, kind: str, size: int) -> Iterator[bytes]:
    offset = 0
    for block in stream(label, size):
        if kind == "text":
            block = block.translate(TEXT_TABLE)
        elif kind == "sparse":
            out = bytearray(block)
            for start in range(0, len(out), RUN):
                if ((offset + start) // RUN) % 2 == 0:
                    end = min(start + RUN, len(out))
                    out[start:end] = bytes(end - start)
            block = bytes(out)
        offset += len(block)
        yield block


def prose(label: str, size: int) -> str:
    return shake(label, size).translate(TEXT_TABLE).decode("ascii")


def source_text(label: str, lines: int) -> bytes:
    raw = shake(label, lines * 10)
    out = []
    for i in range(lines):
        row = raw[i * 10 : i * 10 + 10]
        words = " ".join(WORDS[b % len(WORDS)] for b in row[2 : 3 + row[1] % 8])
        out.append("    " * (row[0] % 4) + words + ENDS[(row[0] >> 2) % 6] + "\n")
    return "".join(out).encode()


def iso(epoch: int) -> str:
    return time.strftime("%Y-%m-%dT%H:%M:%S.000Z", time.gmtime(epoch))


def jsonl(rows: Iterable[object]) -> bytes:
    return b"".join(
        json.dumps(row, separators=(",", ":")).encode() + b"\n" for row in rows
    )


# ---- filesystem --------------------------------------------------------------


def put(path: Path, data: bytes | Iterable[bytes], mode: int = 0o644) -> int:
    path.parent.mkdir(parents=True, exist_ok=True)
    written = 0
    with path.open("wb") as handle:
        for block in [data] if isinstance(data, bytes) else data:
            handle.write(block)
            written += len(block)
    path.chmod(mode)
    return written


def link(path: Path, target: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    os.symlink(target, path)


