#!/usr/bin/env python3
"""Estate-shaped corpus v1 for S1 and S3 (WP0(e): OI-1003-Q19, OI-1003-Q23, R-N13).

R23 corpus v1 (r23_corpus.py) is 23 large regular files, so it never
exercises the per-entry costs of a real agent estate. This script builds a
git-heavy, many-small-file tree that models what bulkload carries from a live
estate. It is deterministic from (--seed, --scale) and sealed by a content
identity. Exact counts per scale are in
docs/evidence/estate-corpus-v1-2026-10-03.md.

Shape. The corpus root models an agent's $HOME:
  git/rNN-*/                 non-bare repositories with history: a --no-ff
                             merge, an annotated and a lightweight tag, an
                             unmerged `side` branch, and a packing profile
                             per repository: loose, packed, or mixed (a pack
                             plus loose objects and refs written after it).
  git/rNN-*.worktrees/<w>    a linked worktree on its own branch, with a
                             commit, an unstaged edit and an untracked file.
  git/rNN-*.worktrees/detached   a detached-HEAD linked worktree. It holds
                             only an untracked file, so `mutate` can move
                             its HEAD.
  git/rNN-*/.claude/worktrees/agent-*   an ignored in-repository worktree.
  git/mirrors/*.git          bare repositories, filled by a push.
  In the main checkouts: real stashes (one with untracked files), a dirty
  index (a staged edit with an unstaged edit on top, a staged new file and an
  intent-to-add entry), unstaged edits, untracked files, ignored build
  outputs, a nested repository inside the work tree, a tracked symlink, an
  executable, and in two repositories a large binary blob.
  projects/*/node_modules    node_modules-like fan-out: scoped packages,
                             nested node_modules, identical LICENSE files and
                             relative .bin symlinks.
  .cache/agent-cache/        a hex fan-out of tiny files.
  data/                      a few large files (random, text, sparse pattern).
  .codex/ .claude/           JSONL transcripts (Codex-like and Claude-like),
                             history, settings and todos. There are .jsonl.zst
                             archives when the `zstd` CLI is on PATH; the
                             devShell has it through stdenv. Without zstd they
                             are skipped and SEAL.json records the note.
  SQLite                     stores in journal_mode=DELETE, plus one WAL
                             crash image (see below).
  Dotfiles, a 0700 .ssh, 0600, 0640 and 0444 files, symlinks (relative to a
  file and to a directory, dangling, absolute, a two-link loop, a link to a
  link), empty directories, unusual-but-legal names and a 32-deep chain.

Determinism. Every generated byte comes from SHAKE-256 (FIPS 202), keyed by
seed, scale and a label. As in r23_corpus.py, nothing uses `random`, so the
output does not depend on the Python version.
Git runs with these settings:
  - an isolated HOME and global config (GIT_CONFIG_GLOBAL);
  - GIT_CONFIG_NOSYSTEM=1, GIT_ATTR_NOSYSTEM=1, TZ=UTC and LC_ALL=C;
  - inherited GIT_* variables dropped, and GIT_CEILING_DIRECTORIES set to the
    corpus root;
  - a fixed author and committer identity;
  - a logical clock: every git call gets the next GIT_AUTHOR_DATE and
    GIT_COMMITTER_DATE, so commits, tags, stashes and every reflog line are
    fixed.
Objects are byte-stable because the global config pins:
  - pack.threads=1, core.looseCompression=1, pack.compression=6, and the pack
    window and depth;
  - pack.writeReverseIndex=true, and no bitmaps;
  - gc.auto=0, maintenance.auto=false, and index.threads=1;
  - no untracked cache, split index or fsmonitor;
  - reflog and prune expiry `never`, so nothing depends on the wall clock.
Repositories are created with an explicit template, so version-dependent
sample hooks do not enter the corpus. They use --object-format=sha1 and
--ref-format=files (git >= 2.45). Their .git/config is rewritten to the text
Linux `git init` writes, so macOS's ignorecase and precomposeunicode lines do
not enter the identity. The corpus repositories have only `.sample` hooks.
Nothing sets core.hooksPath, and nothing passes --no-verify. umask is 022.
Mtimes are left as git and the filesystem set them (so no index is racily
clean); they are not part of the identity.

Identity. MANIFEST.tsv has one line per entry below corpus/, sorted by path
bytes. The columns are path, type (d, f or l), mode, size, SHAKE-256/256
content digest, symlink target and normalisation:
  - mode is the permission bits, or `-` for a symlink, whose mode differs by
    OS;
  - a path or target uses backslash escapes for backslash, control
    characters and undecodable bytes.
The manifest excludes directory sizes, mtimes, ctimes, inodes, devices, link
counts and owners. The identity is the SHAKE-256/256 of MANIFEST.tsv.
SHAKE-256 is r23_corpus.py's generator primitive and is in hashlib; r23's
BLAKE3 needs b3sum, which the devShell does not carry. RECORDED holds the
identities measured with the devShell toolchain. When the toolchain matches,
`generate` compares against them and fails on a mismatch (recorded=False).
Three kinds of file hold bytes that are not a function of the seed, and are
normalised explicitly:
  git-index  every `index` file of a git directory (a main checkout's and
             each linked worktree's). Each entry's stat words (ctime, mtime,
             dev, ino, uid, gid and size) are zeroed, and the trailing
             checksum, which covers them, is dropped. Mode, object id, flags,
             path and the extensions (TREE) stay. An index with a
             stat-bearing extension (UNTR, FSMN or link) is a problem. The
             size column is the real size, because entries are fixed width.
  root       a linked worktree's `.git` file and its administration's `gitdir`
             hold absolute paths. Bulkload's carry resolves them absolutely,
             so relative worktrees are not used. The corpus root recorded in
             SEAL.json is replaced by @CORPUS_ROOT@ before hashing, and the
             size column is the normalised size. Any other file under a git
             directory that contains the root is a problem.
  raw        everything else, including loose objects, packs, .idx, .rev,
             commit-graph, packed-refs, reflogs and the SQLite files.
SQLite DELETE-mode files are stable for one SQLite version; the header
records the writer's version.
The WAL crash image is a main database plus its -wal, copied while the
writing connection was still open:
  - SQLite seeds each new WAL with random salts, so the generator rewrites
    both salts to seed-derived values and recomputes every frame checksum;
  - it then proves that a copy opens with integrity_check ok and the expected
    row count;
  - no -shm is written; it is a lock and index cache that the first opener
    rebuilds.
Caveat: any WAL-aware opener, read-only included (as provider_sqlite's
backup opens it), creates <db>-shm beside the image. A verify after such a
read reports that path as an extra entry.

Not modelled:
  - hardlinks, holes (sparse files), xattrs and ACLs;
  - FIFOs, sockets and devices (bulkload refuses non-regular seats);
  - names with control or format characters (PATH_NOT_PORTABLE).
Case-colliding and NFD names are avoided, so the tree is legal on APFS.

Cross-host. The identity is stable for one toolchain: git (pack layout), its
zlib, SQLite (the header) and zstd (frames). SEAL.json records their
versions, and the devShell pins all of them. A corpus is not relocatable:
linked worktrees point at the absolute path it was generated in. `verify`
still accepts a moved copy (it normalises with the recorded root) and reports
relocated=1, but git must never be run in such a copy.

Mutation (the S3 knob, `--mutate N`, spelled `mutate DEST N`). Round r is the
number of mutations so far, plus one. N operations cycle through, in a
seed-shuffled order with seed-chosen targets:
  edit       overwrite 64 bytes in place;
  append     append a JSONL line;
  new        create a file;
  delete     remove a file;
  commit     a new commit on a repository's unmerged `side` branch, through
             plumbing (side is checked out nowhere);
  head-move  `checkout --detach` in a detached worktree.
It writes DEST/mutations/round-RRRR.json with:
  - the operations, and the identity before and after;
  - the exact manifest difference: added, removed and modified;
  - stat_only: the same manifest row with a new inode, size, mtime or ctime,
    such as a rewritten index or a directory whose listing changed;
  - reads_allowed: the regular files among added, modified and stat_only. An
    S3 rerun may read those files and nothing else.
SEAL.json and MANIFEST.tsv then move to the new identity.

Usage:
  estate_corpus.py generate DEST [--seed S] [--scale small|estate]
      DEST must be new. Writes DEST/corpus, DEST/MANIFEST.tsv, DEST/SEAL.json
      and DEST/README.md.
  estate_corpus.py verify DEST       exit 0 only if DEST/corpus matches its seal
  estate_corpus.py manifest CORPUS [--root R]
  estate_corpus.py mutate DEST N     apply N deterministic changes (S3)
  estate_corpus.py selftest          optional-tier round trip at scale small
"""

