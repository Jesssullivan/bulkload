def sqlite_db(path: Path, label: str, rows: int) -> int:
    """A journal_mode=DELETE store with deleted rows (free pages); returns rows."""
    path.parent.mkdir(parents=True, exist_ok=True)
    det = Det(label)
    con = sqlite3.connect(path, isolation_level=None)
    try:
        con.execute("PRAGMA page_size=4096")
        con.execute("PRAGMA journal_mode=DELETE")
        con.execute(
            "CREATE TABLE threads(id TEXT PRIMARY KEY, created INTEGER, title TEXT)"
        )
        con.execute(
            "CREATE TABLE items(id INTEGER PRIMARY KEY, thread TEXT, role TEXT,"
            " body BLOB)"
        )
        con.execute("CREATE INDEX items_thread ON items(thread)")
        threads = [det.uuid() for _ in range(max(1, rows // 50))]
        con.execute("BEGIN")
        con.executemany(
            "INSERT INTO threads VALUES (?, ?, ?)",
            [
                (t, HISTORY_EPOCH + n, prose(f"{label}/t{n}", 48))
                for n, t in enumerate(threads)
            ],
        )
        con.executemany(
            "INSERT INTO items(thread, role, body) VALUES (?, ?, ?)",
            [
                (
                    det.choice(threads),
                    det.choice(("user", "assistant", "tool")),
                    prose(f"{label}/i{k}", det.between(40, 900)).encode(),
                )
                for k in range(rows)
            ],
        )
        con.execute("COMMIT")
        con.execute("DELETE FROM items WHERE id % 7 = 3")
        con.execute("PRAGMA user_version = 7")
        return con.execute("SELECT count(*) FROM items").fetchone()[0]
    finally:
        con.close()


def wal_checksum(data: bytes, big: bool, s0: int, s1: int) -> tuple[int, int]:
    words = struct.unpack(f"{'>' if big else '<'}{len(data) // 4}I", data)
    for i in range(0, len(words), 2):
        s0 = (s0 + words[i] + s1) & 0xFFFFFFFF
        s1 = (s1 + words[i + 1] + s0) & 0xFFFFFFFF
    return s0, s1


def wal_fix_salts(wal: bytes, salt1: int, salt2: int) -> bytes:
    """Rewrite a fresh WAL's random salts and recompute every checksum."""
    magic, _version, page_size, _seq, old1, old2 = struct.unpack(">6I", wal[:24])
    if magic not in (0x377F0682, 0x377F0683) or (len(wal) - 32) % (24 + page_size):
        raise CorpusError("unexpected WAL layout")
    big = bool(magic & 1)
    header = bytearray(wal[:32])
    struct.pack_into(">II", header, 16, salt1, salt2)
    s0, s1 = wal_checksum(bytes(header[:24]), big, 0, 0)
    struct.pack_into(">II", header, 24, s0, s1)
    out = bytearray(header)
    for pos in range(32, len(wal), 24 + page_size):
        frame = bytearray(wal[pos : pos + 24])
        page = wal[pos + 24 : pos + 24 + page_size]
        if struct.unpack_from(">II", frame, 8) != (old1, old2):
            raise CorpusError("WAL frame from an older generation")
        struct.pack_into(">II", frame, 8, salt1, salt2)
        s0, s1 = wal_checksum(bytes(frame[:8]), big, s0, s1)
        s0, s1 = wal_checksum(page, big, s0, s1)
        struct.pack_into(">II", frame, 16, s0, s1)
        out += frame + page
    return bytes(out)


def sqlite_wal_image(target: Path, label: str, rows: int, scratch: Path) -> None:
    work = scratch / "wal-image"
    work.mkdir()
    db = work / "storage.db"
    sqlite_db(db, label, rows)
    det = Det(f"{label}/wal")
    con = sqlite3.connect(db, isolation_level=None)
    try:
        if con.execute("PRAGMA journal_mode=WAL").fetchone()[0] != "wal":
            raise CorpusError("SQLite refused WAL mode")
        con.execute("PRAGMA wal_autocheckpoint=0")
        for t in range(3):
            con.execute("BEGIN")
            con.executemany(
                "INSERT INTO items(thread, role, body) VALUES (?, ?, ?)",
                [
                    (
                        "wal",
                        "tool",
                        prose(f"{label}/w{t}/{k}", det.between(40, 900)).encode(),
                    )
                    for k in range(40)
                ],
            )
            con.execute("COMMIT")
        expected = con.execute("SELECT count(*) FROM items").fetchone()[0]
        main = db.read_bytes()
        wal = (work / "storage.db-wal").read_bytes()
    finally:
        con.close()
    salt1, salt2 = struct.unpack(">II", shake(f"{label}/salts", 8))
    fixed = wal_fix_salts(wal, salt1, salt2)
    probe = scratch / "wal-probe"
    probe.mkdir()
    (probe / "x.db").write_bytes(main)
    (probe / "x.db-wal").write_bytes(fixed)
    con = sqlite3.connect(probe / "x.db")
    try:
        check = con.execute("PRAGMA integrity_check").fetchone()[0]
        count = con.execute("SELECT count(*) FROM items").fetchone()[0]
    finally:
        con.close()
    if check != "ok" or count != expected:
        raise CorpusError(f"WAL image does not recover: {check} {count}/{expected}")
    put(target, main)
    put(target.with_name(target.name + "-wal"), fixed)


